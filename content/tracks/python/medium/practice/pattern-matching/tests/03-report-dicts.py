assert report({"event": "battery", "level": 19}) == "battery low: 19%", "a level of 19 is low"
assert report({"event": "battery", "level": 20}) == "battery 20%", "a level of 20 is not low"
assert report({"event": "battery", "level": 100, "charging": True}) == "battery 100%", "extra keys do not matter"
assert report({"event": "battery", "level": 0}) == "battery low: 0%", "a level of 0 is low"
assert report({"event": "battery", "level": 12.5}) == "ignored battery event", "a battery level that is not an int is ignored"
assert report({"event": "battery"}) == "ignored battery event", "a battery message without a level is ignored"
assert report({"event": "stuck", "room": "kitchen", "since": "10:02"}) == "stuck in the kitchen", "stuck with extra keys"
assert report({"event": "stuck", "room": 3}) == "ignored stuck event", "a room that is not a str is ignored"
assert report({"event": "bin", "full": True}) == "empty the bin", "a full bin"
assert report({"event": "bin", "full": False}) == "bin ok", "a bin that is not full"
assert report({"event": "bin"}) == "ignored bin event", "a bin message without full is ignored"
assert report({"event": "update", "version": 3}) == "ignored update event", "an unknown event is ignored by name"
assert report({"event": 7}) == "not a message", "an event that is not a str is not a message"
assert report({"level": 50}) == "not a message", "a dict without an event is not a message"
assert report({}) == "not a message", "an empty dict is not a message"
