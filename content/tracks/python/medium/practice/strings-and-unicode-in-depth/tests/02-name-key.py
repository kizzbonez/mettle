assert len(name_key(decomposed)) == 10, "the key is in NFC, with each accented letter as one code point"
assert name_key("JOSÉ") == name_key("josé") == "josé", "upper and lower case give the same key"
assert name_key("GROSS") == name_key("groß"), "casefolding turns ß into ss"
assert name_key("Ana\tLima\n") == "ana lima", "tabs and newlines between and after words count as whitespace"
assert name_key("  Ana    de   Lima  ") == "ana de lima", "runs of spaces become one space and the ends are stripped"
assert name_key("Ingrid") == "ingrid", "a single word only changes case"
assert name_key("") == "", "an empty name gives an empty key"
assert name_key("   ") == "", "a name of only spaces gives an empty key"
